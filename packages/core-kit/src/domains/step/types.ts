export type Step = {
    runId: string;
    index: number;
    kind: 'llm' | 'tool' | 'wait';
    name?: string;
    input?: unknown;
    output?: unknown;
    error?: unknown;
    startedAt: Date;
    finishedAt: Date;
};

/** A stored step: the step and the row's id (a uuid v7 the step service assigns when it appends the step). */
export type StepRecord = Step & {
    id: string;
};
